# Day 2 — Arithmetic and comparison operators

a = 12
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)

print("Is a greater than b?", a > b)
print("Are a and b equal?", a == b)
