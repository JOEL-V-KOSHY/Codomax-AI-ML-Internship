# Day 2 — Common built-in data types

name = "Alex"          # str: text
age = 20               # int: whole number
percentage = 89.5      # float: decimal number
is_enrolled = True     # bool: True or False

print(name, "->", type(name))
print(age, "->", type(age))
print(percentage, "->", type(percentage))
print(is_enrolled, "->", type(is_enrolled))
